    // Load report data
    function loadReportData() {
        $.ajax({
            url: base_url + salaryReportRoute,
            type: 'GET',
            headers: {
                'X-Requested-With': 'XMLHttpRequest',
                'Accept': 'application/json'
            },
            data: {
                outlet_id: outletId,
                from_month: fromMonth,
                to_month: toMonth,
                from_year: fromYear,
                to_year: toYear
            },
            success: function(response) {
                if (response.success && response.data && response.data.salaries) {
                    // Store summary data from controller
                    summaryData = response.data.summary || {};
                    
                    // Update filter info for exports
                    if (response.data.filter_info) {
                        currentFilterInfo = response.data.filter_info;
                        // Map filter values from response
                        currentFilterInfo.from_month = fromMonth || currentFilterInfo.from_month || '';
                        currentFilterInfo.to_month = toMonth || currentFilterInfo.to_month || '';
                        currentFilterInfo.from_year = fromYear || currentFilterInfo.from_year || '';
                        currentFilterInfo.to_year = toYear || currentFilterInfo.to_year || '';
                        updateFilteredInformation(currentFilterInfo);
                    } else {
                        // If no filter_info in response, create it from current values
                        currentFilterInfo = {
                            outlet: null,
                            from_month: fromMonth,
                            to_month: toMonth,
                            from_year: fromYear,
                            to_year: toYear
                        };
                        updateFilteredInformation(currentFilterInfo);
                    }
                    
                    table.clear();
                    table.rows.add(response.data.salaries);
                    table.draw();
                    
                    // Update footer totals from controller summary
                    updateFooterTotals(summaryData);
                } else {
                    table.clear().draw();
                    $('#filteredInformation').hide();
                    updateFooterTotals({
                        total_amount: '0.00'
                    });
                }
            }
        });
    }
  
