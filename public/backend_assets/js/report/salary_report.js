    // Show filter section if filters are applied (on page load)
    function checkAndShowFilters() {
        let fromMonthVal = $('#from_month').val();
        let toMonthVal = $('#to_month').val();
        let fromYearVal = $('#from_year').val();
        let toYearVal = $('#to_year').val();
        let outletIdVal = $('#outlet_id').val();
        
        if (fromMonthVal || toMonthVal || fromYearVal || toYearVal || outletIdVal) {
            // Set global variables before loading data
            outletId = outletIdVal || '';
            fromMonth = fromMonthVal || '';
            toMonth = toMonthVal || '';
            fromYear = fromYearVal || '';
            toYear = toYearVal || '';
            
            $('#filterSection').show();
            initSelect2();
            // Load data if filters are present
            loadReportData();
        }
    }
    
