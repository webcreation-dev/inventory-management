    // Prevent Enter key from submitting form
    $(document).on('keydown', '#filterForm input, #filterForm select', function(e) {
        if (e.key === 'Enter' || e.keyCode === 13) {
            e.preventDefault();
            e.stopPropagation();
            $('#applyFilter').click();
            return false;
        }
    });
  
    // Apply filter
    $(document).on('click', '#applyFilter', function(e) {
        e.preventDefault();
        e.stopPropagation();
        supplierId = $('#supplier_id').val();
        outletId = $('#outlet_id').val();
        dateFrom = $('#date_from').val();
        dateTo = $('#date_to').val();
        type = $('#type').val() || 'All';
        loadReportData();
        return false;
    });
  
    
    
    // Show filter section if filters are applied (on page load)
    function checkAndShowFilters() {
        let dateFromVal = $('#date_from').val();
        let dateToVal = $('#date_to').val();
        let outletIdVal = $('#outlet_id').val();
        let supplierIdVal = $('#supplier_id').val();
        let typeVal = $('#type').val() || 'All';
        
        if (dateFromVal || dateToVal || outletIdVal || supplierIdVal) {
            // Set global variables before loading data
            supplierId = supplierIdVal || '';
            outletId = outletIdVal || '';
            dateFrom = dateFromVal || '';
            dateTo = dateToVal || '';
            type = typeVal;
            
            $('#filterSection').show();
            initSelect2();
            // Load data if filters are present and supplier is selected
            if (supplierId) {
                loadReportData();
            }
        }
    }
    
    // Reinitialize Select2 when filter section is toggled
    $('#filterSection').on('shown.bs.collapse shown', function () {
        initSelect2();
    });
    
