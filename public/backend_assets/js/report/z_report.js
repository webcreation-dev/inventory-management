$(async function () {
    "use strict";

    var base_url = $('#base_url').val() || '';
    var companyName = $('#company_name').val() || '';
    var language_name = $('#language_name').val() || 'en';
    var language_path = '/resources/lang/' + language_name + '.json';
    var language_file = base_url + language_path;
    var language_key = {};

    async function loadLanguage() {
        try {
            var res = await fetch(language_file);
            language_key = await res.json();
        } catch (err) {
            console.error('Failed to load language file:', err);
        }
    }
    await loadLanguage();

    var zReportRoute;
    try {
        zReportRoute = route('report.z-report', {}, false, Ziggy);
    } catch (e) {
        zReportRoute = '/reports/z-report';
    }
    var reportUrl = (String(base_url).replace(/\/?$/, '') + '/' + String(zReportRoute).replace(/^\//, ''));

    var date = '';
    var outletId = '';

    // Store filter info for exports (like Daily Summary Report)
    var currentFilterInfo = {
        outlet: null,
        date: '',
        generated_at: '',
        generated_by: null
    };

    function setDefaultDate() {
        var today = new Date().toISOString().slice(0, 10);
        if (!$('#date').val()) $('#date').val(today);
    }

    function updateFilteredInformation(filterInfo) {
        var html = '';
        if (filterInfo.outlet) {
            html += '<p class="pb-0 mb-0"><strong>' + (language_key.OutletName || 'Outlet Name') + ': </strong> ' + (filterInfo.outlet.name || '-') + '</p>';
            if (filterInfo.outlet.phone) {
                html += '<p class="pb-0 mb-0"><strong>' + (language_key.OutletPhone || 'Outlet Phone') + ': </strong> ' + filterInfo.outlet.phone + '</p>';
            }
            if (filterInfo.outlet.address) {
                html += '<p class="pb-0 mb-0"><strong>' + (language_key.OutletAddress || 'Outlet Address') + ': </strong> ' + filterInfo.outlet.address + '</p>';
            }
        }
        if (filterInfo.date) {
            html += '<p class="pb-0 mb-0"><strong>' + (language_key.Date || 'Date') + ': </strong> ' + filterInfo.date + '</p>';
        }
        if (filterInfo.generated_at) {
            html += '<p class="pb-0 mb-0"><strong>' + (language_key.GeneratedOn || 'Generated on') + ': </strong> ' + filterInfo.generated_at + '</p>';
        }
        if (filterInfo.generated_by && (filterInfo.generated_by.name || filterInfo.generated_by.phone)) {
            var byText = [filterInfo.generated_by.name, filterInfo.generated_by.phone].filter(Boolean).join(', ');
            html += '<p class="pb-0 mb-0"><strong>' + (language_key.GeneratedBy || 'Generated by') + ': </strong> ' + byText + '</p>';
        }
        if (html) {
            $('#filterInfoContent').html(html);
            $('#filteredInformation').show();
        } else {
            $('#filteredInformation').hide();
        }
    }

    function getExportHeader() {
        var header = '<div style="margin-bottom: 20px;">';
        header += '<h3 style="text-align: center; margin-bottom: 15px;">' + (language_key.ZReport || 'Z Report') + '</h3>';
        if (currentFilterInfo.outlet) {
            header += '<p style="margin: 5px 0;"><strong>' + (language_key.OutletName || 'Outlet Name') + ': </strong> ' + (currentFilterInfo.outlet.name || '-') + '</p>';
            if (currentFilterInfo.outlet.phone) {
                header += '<p style="margin: 5px 0;"><strong>' + (language_key.OutletPhone || 'Outlet Phone') + ': </strong> ' + currentFilterInfo.outlet.phone + '</p>';
            }
            if (currentFilterInfo.outlet.address) {
                header += '<p style="margin: 5px 0;"><strong>' + (language_key.OutletAddress || 'Outlet Address') + ': </strong> ' + currentFilterInfo.outlet.address + '</p>';
            }
        }
        if (currentFilterInfo.date) {
            header += '<p style="margin: 5px 0;"><strong>' + (language_key.Date || 'Date') + ': </strong> ' + currentFilterInfo.date + '</p>';
        }
        if (currentFilterInfo.generated_at) {
            header += '<p style="margin: 5px 0;"><strong>' + (language_key.GeneratedOn || 'Generated on') + ': </strong> ' + currentFilterInfo.generated_at + '</p>';
        }
        if (currentFilterInfo.generated_by && (currentFilterInfo.generated_by.name || currentFilterInfo.generated_by.phone)) {
            var byText = [currentFilterInfo.generated_by.name, currentFilterInfo.generated_by.phone].filter(Boolean).join(', ');
            header += '<p style="margin: 5px 0;"><strong>' + (language_key.GeneratedBy || 'Generated by') + ': </strong> ' + byText + '</p>';
        }
        header += '</div>';
        return header;
    }

    function renderAmount(val) {
        if (val == null || val === '') return '0.0';
        if (typeof val === 'number') return Number(val).toFixed(1);
        return String(val);
    }

    function fillReportSections(d) {
        var html;
        if (d.sales_and_taxes_summary && d.sales_and_taxes_summary.length) {
            html = d.sales_and_taxes_summary.map(function (row) {
                return '<tr><td>' + (row.label || '') + '</td><td class="text-end">' + renderAmount(row.amount) + '</td></tr>';
            }).join('');
            $('#zSalesTaxesSummary').html(html);
        } else {
            $('#zSalesTaxesSummary').html('<tr><td colspan="2">-</td></tr>');
        }

        if (d.payment_method_breakdown && d.payment_method_breakdown.length) {
            html = d.payment_method_breakdown.map(function (row) {
                return '<tr><td>' + (row.name || '') + '</td><td class="text-end">' + renderAmount(row.amount) + '</td></tr>';
            }).join('');
            $('#zPaymentMethodBreakdown').html(html);
        } else {
            $('#zPaymentMethodBreakdown').html('<tr><td colspan="2">-</td></tr>');
        }

        if (d.payment_other_currencies && d.payment_other_currencies.length) {
            html = d.payment_other_currencies.map(function (row) {
                return '<tr><td>' + (row.name || row.currency || '') + '</td><td class="text-end">' + renderAmount(row.amount) + '</td></tr>';
            }).join('');
            $('#zPaymentOtherCurrencies').html(html);
        } else {
            $('#zPaymentOtherCurrencies').html('<tr><td colspan="2">-</td></tr>');
        }

        if (d.item_wise_sales) {
            var qty = d.item_wise_sales.quantity_total != null ? renderAmount(d.item_wise_sales.quantity_total) : '';
            html = '<tr><td>' + qty + '</td><td class="text-end">' + renderAmount(d.item_wise_sales.amount_total) + '</td></tr>';
            $('#zItemWiseSales').html(html);
        } else {
            $('#zItemWiseSales').html('<tr><td></td><td class="text-end">0.0</td></tr>');
        }

        if (d.purchase_paid && d.purchase_paid.length) {
            html = d.purchase_paid.map(function (row) {
                return '<tr><td>' + (row.label || '') + '</td><td class="text-end">' + renderAmount(row.amount) + '</td></tr>';
            }).join('');
            $('#zPurchasePaid').html(html);
        } else {
            $('#zPurchasePaid').html('<tr><td colspan="2">-</td></tr>');
        }

        if (d.expense && d.expense.length) {
            html = d.expense.map(function (row) {
                return '<tr><td>' + (row.label || '') + '</td><td class="text-end">' + renderAmount(row.amount) + '</td></tr>';
            }).join('');
            $('#zExpense').html(html);
        } else {
            $('#zExpense').html('<tr><td colspan="2">-</td></tr>');
        }

        if (d.supplier_payment && d.supplier_payment.length) {
            html = d.supplier_payment.map(function (row) {
                return '<tr><td>' + (row.label || '') + '</td><td class="text-end">' + renderAmount(row.amount) + '</td></tr>';
            }).join('');
            $('#zSupplierPayment').html(html);
        } else {
            $('#zSupplierPayment').html('<tr><td colspan="2">-</td></tr>');
        }

        if (d.customer_due_receives && d.customer_due_receives.length) {
            html = d.customer_due_receives.map(function (row) {
                return '<tr><td>' + (row.label || '') + '</td><td class="text-end">' + renderAmount(row.amount) + '</td></tr>';
            }).join('');
            $('#zCustomerDueReceives').html(html);
        } else {
            $('#zCustomerDueReceives').html('<tr><td colspan="2">-</td></tr>');
        }

        if (d.total_in_hand && d.total_in_hand.length) {
            html = [];
            d.total_in_hand.forEach(function (method) {
                var rows = (method.transactions || []).map(function (t) {
                    return '<tr><td></td><td>' + (t.name || '') + '</td><td class="text-end">' + renderAmount(t.amount) + '</td></tr>';
                }).join('');
                html.push('<tr><td><strong>' + (method.payment_method || '') + '</strong></td><td></td><td></td></tr>' + rows);
            });
            $('#zTotalInHand').html(html.join(''));
        } else {
            $('#zTotalInHand').html('<tr><td colspan="3">-</td></tr>');
        }

        if (d.in_hand_summary && d.in_hand_summary.length) {
            html = d.in_hand_summary.map(function (row) {
                return '<tr><td>' + (row.name || '') + '</td><td class="text-end">' + renderAmount(row.amount) + '</td></tr>';
            }).join('');
            $('#zInHandSummary').html(html);
        } else {
            $('#zInHandSummary').html('<tr><td colspan="2">-</td></tr>');
        }
    }

    function loadZReport() {
        date = $('#date').val();
        outletId = $('#outlet_id').val() || '';
        if (!date || !outletId) {
            Swal.fire({
                icon: 'warning',
                title: language_key.Warning || 'Warning',
                text: language_key.DateAndOutletRequired || 'Date and Outlet are required',
                confirmButtonText: language_key.OK || 'OK'
            });
            return;
        }

        $('#zReportLoading').show();
        $('#zReportEmpty').hide();
        $('#zReportContentWrapper').hide();
        $('#filteredInformation').hide();

        $.ajax({
            url: reportUrl,
            type: 'GET',
            headers: { 'X-Requested-With': 'XMLHttpRequest', 'Accept': 'application/json' },
            data: { date: date, outlet_id: outletId },
            success: function (res) {
                $('#zReportLoading').hide();
                if (!res.success || !res.data) {
                    $('#zReportEmptyMsg').text(res.message || (language_key.FailedToLoadReport || 'Failed to load report.'));
                    $('#zReportEmpty').show();
                    $('#zReportContentWrapper').hide();
                    return;
                }
                var d = res.data;
                if (d.filter_info) {
                    currentFilterInfo = d.filter_info;
                    updateFilteredInformation(currentFilterInfo);
                } else {
                    currentFilterInfo = { outlet: null, date: d.date || date, generated_at: '', generated_by: null };
                    updateFilteredInformation(currentFilterInfo);
                }
                fillReportSections(d);
                $('#zReportEmpty').hide();
                $('#zReportContentWrapper').show();
            },
            error: function (xhr) {
                $('#zReportLoading').hide();
                $('#zReportEmpty').show();
                $('#zReportContentWrapper').hide();
                $('#filteredInformation').hide();
                var msg = (xhr.responseJSON && xhr.responseJSON.message) ? xhr.responseJSON.message : (language_key.FailedToLoadReport || 'Failed to load report.');
                $('#zReportEmptyMsg').text(msg);
            }
        });
    }

    // Filter button: slide toggle filter section (like Daily Summary Report)
    $(document).on('click', '#zReportFilterBtn', function () {
        $('#filterSection').slideToggle();
    });

    // Export: Print (like Daily Summary - header + content)
    $(document).on('click', '[data-export="print"]', function (e) {
        e.preventDefault();
        if (!currentFilterInfo.date) {
            Swal.fire({ icon: 'warning', title: language_key.Warning || 'Warning', text: language_key.GenerateReportFirst || 'Generate the report first.', confirmButtonText: language_key.OK || 'OK' });
            return;
        }
        var printWin = window.open('', '_blank');
        printWin.document.write('<html><head><title>' + (language_key.ZReport || 'Z Report') + '</title><link href="' + base_url + '/public/backend_assets/vendor/css/rtl/core.css" rel="stylesheet"/></head><body>');
        printWin.document.write(getExportHeader());
        printWin.document.write('<div class="z-report-container">' + $('#zReportContent').html() + '</div>');
        printWin.document.write('</body></html>');
        printWin.document.close();
        printWin.focus();
        setTimeout(function () { printWin.print(); printWin.close(); }, 250);
    });

    // Export: Excel - header lines + table data as CSV-style (like Daily Summary messageTop)
    $(document).on('click', '[data-export="excel"]', function (e) {
        e.preventDefault();
        if (!currentFilterInfo.date) {
            Swal.fire({ icon: 'warning', title: language_key.Warning || 'Warning', text: language_key.GenerateReportFirst || 'Generate the report first.', confirmButtonText: language_key.OK || 'OK' });
            return;
        }
        var lines = [(language_key.ZReport || 'Z Report')];
        if (currentFilterInfo.outlet) {
            lines.push((language_key.OutletName || 'Outlet Name') + ': ' + (currentFilterInfo.outlet.name || '-'));
            if (currentFilterInfo.outlet.phone) lines.push((language_key.OutletPhone || 'Outlet Phone') + ': ' + currentFilterInfo.outlet.phone);
            if (currentFilterInfo.outlet.address) lines.push((language_key.OutletAddress || 'Outlet Address') + ': ' + currentFilterInfo.outlet.address);
        }
        if (currentFilterInfo.date) lines.push((language_key.Date || 'Date') + ': ' + currentFilterInfo.date);
        if (currentFilterInfo.generated_at) lines.push((language_key.GeneratedOn || 'Generated on') + ': ' + currentFilterInfo.generated_at);
        if (currentFilterInfo.generated_by && (currentFilterInfo.generated_by.name || currentFilterInfo.generated_by.phone)) {
            lines.push((language_key.GeneratedBy || 'Generated by') + ': ' + [currentFilterInfo.generated_by.name, currentFilterInfo.generated_by.phone].filter(Boolean).join(', '));
        }
        lines.push('');
        var $content = $('#zReportContent');
        $content.find('table').each(function () {
            var $t = $(this);
            $t.find('tr').each(function () {
                var row = [];
                $(this).find('th, td').each(function () { row.push('"' + String($(this).text()).replace(/"/g, '""') + '"'); });
                if (row.length) lines.push(row.join(','));
            });
            lines.push('');
        });
        var blob = new Blob([lines.join('\r\n')], { type: 'text/csv;charset=utf-8;' });
        var link = document.createElement('a');
        link.href = URL.createObjectURL(blob);
        link.download = 'z-report-' + (currentFilterInfo.date || 'report').replace(/\//g, '-') + '.csv';
        link.click();
        URL.revokeObjectURL(link.href);
    });

    // Export: PDF (simple - open print dialog which user can save as PDF, or use pdfMake if available)
    $(document).on('click', '[data-export="pdf"]', function (e) {
        e.preventDefault();
        if (!currentFilterInfo.date) {
            Swal.fire({ icon: 'warning', title: language_key.Warning || 'Warning', text: language_key.GenerateReportFirst || 'Generate the report first.', confirmButtonText: language_key.OK || 'OK' });
            return;
        }
        var printWin = window.open('', '_blank');
        printWin.document.write('<html><head><title>' + (language_key.ZReport || 'Z Report') + '</title></head><body>');
        printWin.document.write(getExportHeader());
        printWin.document.write('<div class="z-report-container">' + $('#zReportContent').html() + '</div>');
        printWin.document.write('</body></html>');
        printWin.document.close();
        printWin.focus();
        setTimeout(function () { printWin.print(); printWin.close(); }, 250);
    });

    function initSelect2() {
        if ($('#outlet_id').length && !$('#outlet_id').hasClass('select2-hidden-accessible')) {
            $('#outlet_id').select2({
                dropdownParent: $('#filterSection'),
                width: '100%',
                placeholder: language_key.SelectOutlet || 'Select Outlet',
                allowClear: false
            });
        }
    }

    $('#applyFilter').on('click', function (e) {
        e.preventDefault();
        loadZReport();
    });

    $(document).on('submit', '#filterForm', function (e) {
        e.preventDefault();
        e.stopPropagation();
        return false;
    });
    $(document).on('keydown', '#filterForm input, #filterForm select', function (e) {
        if (e.key === 'Enter' || e.keyCode === 13) {
            e.preventDefault();
            $('#applyFilter').click();
            return false;
        }
    });

    function checkAndShowFilters() {
        var dateVal = $('#date').val();
        var outletIdVal = $('#outlet_id').val();
        if (dateVal && outletIdVal) {
            date = dateVal;
            outletId = outletIdVal;
            $('#filterSection').show();
            initSelect2();
            loadZReport();
        }
    }

    $('#filterSection').on('shown.bs.collapse shown', function () {
        initSelect2();
    });

    setDefaultDate();
    initSelect2();
    checkAndShowFilters();

    if (!$('#date').val() || !$('#outlet_id').val()) {
        $('#zReportEmpty').show();
        $('#zReportContentWrapper').hide();
        $('#zReportEmptyMsg').text(language_key.ClickFilterSelectDateOutlet || 'Click Filter, select Date and Outlet, then Apply Filter to view the Z Report.');
    }
});
